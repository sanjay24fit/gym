/**
 * Translates a single text string into Hinglish.
 */
export function translateToHinglish(text) {
  if (!text || typeof text !== 'string') return text
  const trimmed = text.trim()
  if (!trimmed) return text

  // 1. Direct dictionary match
  if (Object.prototype.hasOwnProperty.call(HINGLISH_DICTIONARY, trimmed)) {
    return HINGLISH_DICTIONARY[trimmed]
  }

  // 2. Pattern matching
  for (const [pattern, replacement] of HINGLISH_PATTERNS) {
    if (pattern.test(trimmed)) {
      return trimmed.replace(pattern, replacement)
    }
  }

  return text
}

// Global state tracking for DOM observer & clean restoration
let activeObserver = null
const originalNodeValues = new WeakMap()
let isTranslating = false

function shouldSkipElement(el) {
  if (!el || !el.tagName) return true
  const tag = el.tagName.toUpperCase()
  return (
    tag === 'SCRIPT' ||
    tag === 'STYLE' ||
    tag === 'TEXTAREA' ||
    tag === 'INPUT' ||
    tag === 'CODE' ||
    tag === 'PRE' ||
    el.classList?.contains('goog-te-combo') ||
    el.closest?.('#google_translate_element') ||
    el.closest?.('.lang-grid') // preserve native language names in language picker
  )
}

function translateTextNode(node) {
  if (!node || node.nodeType !== 3) return
  const parent = node.parentElement
  if (!parent || shouldSkipElement(parent)) return

  const original = node.nodeValue
  if (!original || !original.trim()) return

  // Store original English text if not already stored
  if (!originalNodeValues.has(node)) {
    originalNodeValues.set(node, original)
  }

  const baseText = originalNodeValues.get(node) || original
  const trimmed = baseText.trim()
  const translated = translateToHinglish(trimmed)

  if (translated && translated !== trimmed) {
    const leading = baseText.match(/^\s*/)[0]
    const trailing = baseText.match(/\s*$/)[0]
    const nextVal = leading + translated + trailing
    if (node.nodeValue !== nextVal) {
      node.nodeValue = nextVal
    }
  }
}

function translateAttributes(el) {
  if (!el || !el.getAttribute) return
  if (shouldSkipElement(el)) return

  // Placeholder
  const placeholder = el.getAttribute('placeholder')
  if (placeholder && placeholder.trim()) {
    const translated = translateToHinglish(placeholder.trim())
    if (translated && translated !== placeholder) {
      el.setAttribute('placeholder', translated)
    }
  }

  // Title
  const title = el.getAttribute('title')
  if (title && title.trim()) {
    const translated = translateToHinglish(title.trim())
    if (translated && translated !== title) {
      el.setAttribute('title', translated)
    }
  }
}

function walkAndTranslate(root) {
  if (!root) return
  if (root.nodeType === 3) {
    translateTextNode(root)
    return
  }
  if (root.nodeType !== 1) return
  if (shouldSkipElement(root)) return

  translateAttributes(root)

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const p = node.parentElement
      if (!p || shouldSkipElement(p)) return NodeFilter.FILTER_REJECT
      return NodeFilter.FILTER_ACCEPT
    },
  })

  let current
  while ((current = walker.nextNode())) {
    translateTextNode(current)
  }
}

/**
 * Activates Hinglish localization across the entire DOM.
 * Returns a cleanup function that restores the original text and disconnects the observer.
 */
export function applyHinglishToDOM() {
  if (typeof document === 'undefined') return () => {}

  // Disconnect any existing observer
  if (activeObserver) {
    activeObserver.disconnect()
    activeObserver = null
  }

  isTranslating = true
  try {
    walkAndTranslate(document.body)
  } finally {
    isTranslating = false
  }

  // Observe ongoing DOM changes (tab switches, modals, queries, dynamic updates)
  const observer = new MutationObserver((mutations) => {
    if (isTranslating) return
    isTranslating = true
    try {
      for (const m of mutations) {
        if (m.type === 'childList') {
          for (let i = 0; i < m.addedNodes.length; i++) {
            walkAndTranslate(m.addedNodes[i])
          }
        } else if (m.type === 'characterData') {
          translateTextNode(m.target)
        }
      }
    } finally {
      isTranslating = false
    }
  })

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
  })

  activeObserver = observer

  // Return cleanup function to restore English
  return () => {
    if (activeObserver) {
      activeObserver.disconnect()
      activeObserver = null
    }
    // Re-walk DOM and restore cached original English values
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT)
    let current
    while ((current = walker.nextNode())) {
      if (originalNodeValues.has(current)) {
        current.nodeValue = originalNodeValues.get(current)
      }
    }
  }
}
